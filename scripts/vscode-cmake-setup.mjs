// Configure VS Code's CMake Tools for the PTPN analyzer engine.
//
// This writes two machine-local files and never touches the unified `just`
// build tree (`build/ptpn`, MSVC static) or any release artifact:
//
//   engines/prioritized-tpn/CMakeUserPresets.json  (ignored by the engine repo)
//   .vscode/settings.json                          (points CMake Tools at it)
//
// It pins the CLion-bundled MinGW + Ninja and the D:/vcpkg checkout that the
// rest of the toolchain detection already uses, so vcpkg detects g++ instead of
// falling back to MSVC for the x64-mingw-dynamic triplet.
//
// Run once: node scripts/vscode-cmake-setup.mjs
// Then in VS Code: "CMake: Select Configure Preset" -> vscode-windows-debug.

import fs from "node:fs";
import path from "node:path";

import { detectToolchain, ensureDir, paths } from "./lib.mjs";

const toolchain = detectToolchain({ required: false });
const missing = [];
if (!toolchain.mingwBin) missing.push("MinGW g++ (PTPN_MINGW_BIN)");
if (!toolchain.ninja) missing.push("Ninja (NINJA)");
if (!toolchain.cmake) missing.push("CMake (CMAKE)");
if (!toolchain.vcpkgRoot) missing.push("vcpkg checkout (VCPKG_ROOT)");
if (missing.length > 0) {
  console.error(`error: missing tools: ${missing.join(", ")}`);
  console.error("Set them in .env.local or the environment, then re-run this script.");
  process.exit(1);
}

const slash = (value) => value.replace(/\\/g, "/");
const mingw = slash(toolchain.mingwBin);
const ninja = slash(toolchain.ninja);
const cmake = slash(toolchain.cmake);
const vcpkg = slash(toolchain.vcpkgRoot);
const engineDir = paths.ptpnEngine;

const presets = {
  version: 6,
  cmakeMinimumRequired: { major: 3, minor: 27, patch: 0 },
  configurePresets: [
    {
      name: "vscode-windows-debug",
      displayName: "Windows MinGW Debug (VS Code, local)",
      description:
        "CLion-bundled MinGW + Ninja with vcpkg x64-mingw-dynamic. Generated by scripts/vscode-cmake-setup.mjs; not the release build.",
      inherits: "windows-debug",
      binaryDir: "${sourceDir}/cmake-build-vscode",
      cacheVariables: {
        CMAKE_C_COMPILER: `${mingw}/gcc.exe`,
        CMAKE_CXX_COMPILER: `${mingw}/g++.exe`,
        CMAKE_MAKE_PROGRAM: ninja,
        CMAKE_TOOLCHAIN_FILE: `${vcpkg}/scripts/buildsystems/vcpkg.cmake`,
        VCPKG_TARGET_TRIPLET: "x64-mingw-dynamic",
        VCPKG_APPLOCAL_DEPS: "ON",
      },
      environment: {
        VCPKG_ROOT: vcpkg,
        PATH: `${mingw};${path.posix.dirname(ninja)};$penv{PATH}`,
      },
    },
  ],
  buildPresets: [
    {
      name: "vscode-windows-debug",
      configurePreset: "vscode-windows-debug",
    },
  ],
  testPresets: [
    {
      name: "vscode-windows-debug",
      configurePreset: "vscode-windows-debug",
      output: { outputOnFailure: true },
    },
  ],
};

const presetPath = path.join(engineDir, "CMakeUserPresets.json");
fs.writeFileSync(presetPath, `${JSON.stringify(presets, null, 2)}\n`, "utf8");
console.log(`wrote ${presetPath}`);

const settingsPath = path.join(paths.root, ".vscode", "settings.json");
ensureDir(path.dirname(settingsPath));
let settings = {};
if (fs.existsSync(settingsPath)) {
  try {
    settings = JSON.parse(fs.readFileSync(settingsPath, "utf8"));
  } catch (error) {
    console.error(`warning: ${settingsPath} is not valid JSON (${error.message}); rewriting it`);
    settings = {};
  }
}
settings["cmake.sourceDirectory"] = "${workspaceFolder}/engines/prioritized-tpn";
settings["cmake.useCMakePresets"] = "always";
settings["cmake.configurePreset"] = "vscode-windows-debug";
settings["cmake.buildPreset"] = "vscode-windows-debug";
settings["cmake.testPreset"] = "vscode-windows-debug";
settings["cmake.cmakePath"] = cmake;
fs.writeFileSync(settingsPath, `${JSON.stringify(settings, null, 2)}\n`, "utf8");
console.log(`updated ${settingsPath}`);
console.log(`
Next:
  1. Reload the VS Code window (Command Palette: "Developer: Reload Window").
  2. "CMake: Select Configure Preset" -> vscode-windows-debug (if not already).
  3. Configure/Build from the CMake Tools status bar, or:
       cmake --preset vscode-windows-debug
       cmake --build --preset vscode-windows-debug
       ctest --preset vscode-windows-debug
     (run inside engines/prioritized-tpn)

This builds x64-mingw-dynamic into engines/prioritized-tpn/cmake-build-vscode and does
not participate in the \`just\` release pipeline, which stays on MSVC x64-windows-static.`);
